/* Builds figma/velo-landing.html — a static snapshot of the current landing page
   for Figma import (html.to.design): scripts stripped, final values baked in,
   motion disabled. Re-run after editing the landing page:  node build-landing-snapshot.mjs */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
let html = readFileSync(join(here, "..", "index.html"), "utf8");

/* 1. asset paths up one level (snapshot lives in website/figma/) */
html = html.replaceAll('href="assets/', 'href="../assets/');
html = html.replaceAll('src="assets/', 'src="../assets/');

/* 2. strip scripts — no counters/observers in the snapshot */
html = html.replace(/<script>[\s\S]*?<\/script>/g, "");

/* 3. bake final counter/chart values (exact literal matches) */
const finals = [
  ['data-c="300" data-s="+">0<', 'data-c="300" data-s="+">300+<'],
  ['data-c="4" data-pad="2">0<', 'data-c="4" data-pad="2">04<'],
  ['data-c="100" data-s="%">0<', 'data-c="100" data-s="%">100%<'],
  ['data-c="75" data-p="&gt;" data-s="%">0<', 'data-c="75" data-p="&gt;" data-s="%">&gt;75%<'],
  ['data-c="70" data-s="%">0%<', 'data-c="70" data-s="%">70%<'],
  ['data-c="1.73" data-dec="2" data-p="$" data-s="T">$0.00T<', 'data-c="1.73" data-dec="2" data-p="$" data-s="T">$1.73T<'],
  ['data-c="2.5" data-dec="1" data-s="H">0H<', 'data-c="2.5" data-dec="1" data-s="H">2.5H<'],
  ['data-c="32" data-s="%">0%<', 'data-c="32" data-s="%">32%<'],
  ['data-c="550" data-s="H/YR">0<', 'data-c="550" data-s="H/YR">550H/YR<'],
  ['data-c="88" data-s="%">0%<', 'data-c="88" data-s="%">88%<']
];
for (const [from, to] of finals) {
  if (!html.includes(from)) console.warn("WARN pattern not found:", from);
  html = html.replaceAll(from, to);
}

/* 4. freeze motion at final states */
const override = `
/* figma static snapshot — final states, motion off */
*{animation:none!important;transition:none!important}
.hero .wrap>*,[data-reveal]{opacity:1!important;transform:none!important}
.ring .arc{stroke-dashoffset:46.75px!important}
.shift__fill{width:31.25%!important}
.d-waste{stroke-dasharray:19.79px 420.03px!important}
.d-margin{stroke-dasharray:30.35px 409.47px!important;stroke-dashoffset:-19.79px!important}
.d-rest{stroke-dasharray:389.68px 50.14px!important;stroke-dashoffset:-50.14px!important}
.mq-track{transform:none!important}
</style>`;
html = html.replace("</style>", override);

/* 5. label it */
html = html.replace("<title>", "<!-- Figma snapshot of the landing page — generated by build-landing-snapshot.mjs -->\n<title>");
html = html.replace("</title>", " — Figma Snapshot</title>");

writeFileSync(join(here, "velo-landing.html"), html);
console.log("wrote velo-landing.html (" + Math.round(html.length / 1024) + " KB)");
